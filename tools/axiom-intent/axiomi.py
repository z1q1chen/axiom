#!/usr/bin/env python3
"""axiomi: Axiom in its intent-first form.

The design conclusion this implements: the forcing lives in
the intent loop, not in the target language. So:

  - The INTENT FILE is the only source of truth. It declares
    structs (with invariants), functions (with requires /
    ensures written at intent level), decisions (options +
    defaults), and properties (each with named evidence).
  - Rust code is a BUILD ARTIFACT generated from the intent
    file. It is never hand-edited; a lockfile records its
    hash, and `check` detects out-of-loop edits (BYPASSED).
  - Contracts are lowered into the generated Rust: requires
    asserted on entry, ensures asserted on the single exit
    path (bodies are wrapped), struct invariants asserted at
    function boundaries.
  - Evidence tiers: runtime-checked (scenario snippets and
    lowered contracts), bounded (pure int functions exhausted
    over a bounded domain), UNCHECKED (evidence "none").
  - THE FORCING: a property with no evidence FAILS the build
    unless the intent file carries an explicit signed
    acceptance ("accepted": true + note). Skipping a
    guarantee is a recorded decision, never an oversight.

Usage:
  python3 axiomi.py build <name>.intent.json
  python3 axiomi.py check <name>.intent.json   (integrity only)

Contract expressions are written in a Rust-compatible subset
(arithmetic, comparisons, &&, ||, !, field access, `result`
in ensures). Function bodies are Rust snippets drafted by the
AI half of the loop; this tool pins, generates, runs, tiers,
and reports — it authors nothing.
"""

import hashlib
import itertools
import json
import os
import re
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))


def sha(text):
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def find_rustc():
    env = os.environ.get("RUSTC")
    if env:
        return env
    cand = os.path.expanduser("~/.cargo/bin/rustc")
    if os.path.exists(cand):
        return cand
    return "rustc"


def rustc_build(src_path, out_path):
    p = subprocess.run(
        [find_rustc(), "--edition", "2021", "-O", src_path, "-o", out_path],
        capture_output=True, text=True)
    return p.returncode, p.stderr


# ---------------- code generation ----------------

def gen_structs(spec):
    out = []
    for s in spec.get("structs", []):
        fields = "\n".join(f"    pub {n}: {t}," for n, t in s["fields"])
        out.append(f"#[derive(Clone, Debug)]\npub struct {s['name']} {{\n{fields}\n}}")
        if s.get("invariant"):
            binds = "\n".join(
                f"    let {n} = v.{n}.clone();" for n, _ in s["fields"])
            out.append(
                f"pub fn invariant_{s['name']}(v: &{s['name']}) -> bool {{\n"
                f"{binds}\n    ({s['invariant']})\n}}")
            out.append(
                f"pub fn assert_invariant_{s['name']}(v: &{s['name']}, ctx: &str) {{\n"
                f"    assert!(invariant_{s['name']}(v), "
                f"\"invariant violated ({{}}) for {s['name']}: {s['invariant']}\", ctx);\n}}")
    return "\n\n".join(out)


def gen_function(spec, fn, struct_names):
    params = ", ".join(f"{n}: {t}" for n, t in fn["params"])
    sig = f"fn {fn['name']}_impl({params})"
    if fn.get("returns"):
        sig += f" -> {fn['returns']}"
    impl = f"{sig} {{\n{fn['body']}\n}}"
    parts = [impl]
    if fn.get("pure"):
        reqs = fn.get("requires", [])
        if reqs:
            cond = " && ".join(f"({r})" for r in reqs)
            parts.append(
                f"pub fn {fn['name']}_requires({params}) -> bool {{ {cond} }}")
    wparams = params
    call_args = ", ".join(n for n, _ in fn["params"])
    body = []
    for r in fn.get("requires", []):
        body.append(
            f"    assert!({r}, \"requires violated in {fn['name']}: {r}\");")
    for n, t in fn["params"]:
        if t in struct_names:
            body.append(f"    assert_invariant_{t}(&{n}, \"entry {fn['name']}\");")
    if fn.get("returns"):
        body.append(f"    let result = {fn['name']}_impl({call_args});")
        if fn["returns"] in struct_names:
            body.append(
                f"    assert_invariant_{fn['returns']}(&result, \"exit {fn['name']}\");")
        for e in fn.get("ensures", []):
            body.append(
                f"    assert!({e}, \"ensures violated in {fn['name']}: {e}\");")
        body.append("    result")
    else:
        body.append(f"    {fn['name']}_impl({call_args});")
    wsig = f"pub fn {fn['name']}({wparams})"
    if fn.get("returns"):
        wsig += f" -> {fn['returns']}"
    parts.append(f"{wsig} {{\n" + "\n".join(body) + "\n}")
    return "\n\n".join(parts)


def gen_module(spec):
    struct_names = {s["name"] for s in spec.get("structs", [])}
    header = (f"// GENERATED BY axiomi FROM {spec['module']}.intent.json"
              " — DO NOT EDIT.\n"
              "// The intent file is the source of truth; edits here are\n"
              "// detected by `axiomi.py check` and overwritten by build.\n")
    parts = [header, gen_structs(spec)]
    for fn in spec.get("functions", []):
        parts.append(gen_function(spec, fn, struct_names))
    return "\n\n".join(p for p in parts if p) + "\n"


def gen_scenario_main(spec, module_file):
    blocks = []
    for p in spec.get("properties", []):
        if p["evidence"] != "scenario":
            continue
        blocks.append(
            f"    let r = panic::catch_unwind(|| {{\n{p['scenario']}\n    }});\n"
            f"    if r.is_ok() {{ println!(\"PROP {p['id']} OK\"); }}"
            f" else {{ fails += 1; println!(\"PROP {p['id']} FAIL\"); }}")
    return (f'include!("{module_file}");\n'
            "use std::panic;\n"
            "fn main() {\n"
            "    panic::set_hook(Box::new(|_| {}));\n"
            "    let mut fails = 0;\n"
            + "\n".join(blocks)
            + "\n    std::process::exit(if fails == 0 { 0 } else { 1 });\n}\n")


DOMAIN_CAP = 20000


def domain_for(fn):
    lits = set()
    for r in fn.get("requires", []):
        for m in re.findall(r"-?\d+", r):
            v = int(m)
            lits.update((v - 1, v, v + 1))
    base = sorted(set(range(-3, 4)) | lits)
    n = len(fn["params"])
    if len(base) ** n <= DOMAIN_CAP:
        return base
    small = sorted(set((-1, 0, 1)) | lits)
    if len(small) ** n <= DOMAIN_CAP:
        return small
    return None


def gen_verify_main(spec, module_file):
    fns = {f["name"]: f for f in spec.get("functions", [])}
    wanted = []
    for p in spec.get("properties", []):
        if p["evidence"] == "verify":
            fn = fns[p["fn"]]
            if all(t == "i64" for _, t in fn["params"]):
                wanted.append((p, fn))
    parts = [f'include!("{module_file}");', "use std::panic;"]
    for p, fn in wanted:
        dom = domain_for(fn)
        if dom is None:
            parts.append(
                f'fn verify_{fn["name"]}() {{ println!("VERIFY {fn["name"]} '
                'DOMAIN_TOO_LARGE"); }')
            continue
        args = ", ".join(f"a{i}" for i in range(len(fn["params"])))
        loops = ""
        indent = "    "
        for i in range(len(fn["params"])):
            loops += f"{indent}for a{i} in {dom} {{\n"
            indent += "    "
        req_fn = f"{fn['name']}_requires"
        has_req = bool(fn.get("requires"))
        skip = (f"if !{req_fn}({args}) {{ excluded += 1; }} else "
                if has_req else "")
        parts.append(
            f"fn verify_{fn['name']}() {{\n"
            f"    let mut cases: i64 = 0; let mut excluded: i64 = 0;\n"
            f"    let mut failed: i64 = 0; let mut first = String::new();\n"
            + loops
            + f"{indent}{skip}{{ cases += 1;\n"
            + f"{indent}    let r = panic::catch_unwind(|| {fn['name']}({args}));\n"
            + f"{indent}    if r.is_err() {{ failed += 1; "
            + f"if first.is_empty() {{ first = format!(\"{{:?}}\", ({args},)); }} }} }}\n"
            + "".join("    }\n" for _ in range(len(fn["params"])))
            + f"    println!(\"VERIFY {fn['name']} cases={{}} excluded={{}} "
              "failed={} first={}\", cases, excluded, failed, first);\n}")
    calls = "\n".join(f"    verify_{fn['name']}();" for _, fn in wanted)
    parts.append("fn main() {\n    panic::set_hook(Box::new(|_| {}));\n"
                 + calls + "\n}\n")
    return "\n\n".join(parts) + "\n"


# ---------------- the loop ----------------

def load(intent_path):
    with open(intent_path, encoding="utf-8") as f:
        return json.load(f)


def paths_for(intent_path):
    d = os.path.dirname(os.path.abspath(intent_path))
    spec = load(intent_path)
    mod = spec["module"]
    return spec, d, {
        "rs": os.path.join(d, f"{mod}.rs"),
        "lock": os.path.join(d, f"{mod}.intent.lock.json"),
        "spec_md": os.path.join(d, "SPEC.md"),
        "evidence_md": os.path.join(d, "EVIDENCE.md"),
        "ledger": os.path.join(d, "ledger.json"),
    }


def cmd_check(intent_path):
    spec, d, P = paths_for(intent_path)
    if not os.path.exists(P["lock"]) or not os.path.exists(P["rs"]):
        print("integrity: NO_LOCK (never built)")
        return 1
    with open(P["lock"], encoding="utf-8") as f:
        lock = json.load(f)
    with open(P["rs"], encoding="utf-8") as f:
        rs_hash = sha(f.read())
    with open(intent_path, encoding="utf-8") as f:
        intent_hash = sha(f.read())
    if rs_hash != lock["artifact_sha256"]:
        print("integrity: BYPASSED — generated Rust differs from the "
              "lockfile; it was edited outside the intent loop")
        return 1
    if intent_hash != lock["intent_sha256"]:
        print("integrity: STALE — intent file changed since last build; "
              "rebuild to regenerate")
        return 1
    print("integrity: IN-LOOP — artifact matches the intent file")
    return 0


def write_spec_md(spec, P):
    unanswered = [x for x in spec.get("decisions", [])
                  if x.get("answer") is None]
    lines = [f"# Spec: {spec['module']}", "", spec["intent"].strip(), "",
             "## Decisions", "",
             "| id | question | options | chosen | source |",
             "|---|---|---|---|---|"]
    for d in spec.get("decisions", []):
        chosen = d.get("answer") if d.get("answer") is not None else d["default"]
        origin = ("answered" if d.get("answer") is not None
                  else "DEFAULT (accepted risk)")
        lines.append(f"| {d['id']} | {d['question']} | "
                     f"{', '.join(d['options'])} | {chosen} | {origin} |")
    lines += ["", "## Functions and their contracts", ""]
    for fn in spec.get("functions", []):
        lines.append(f"- **{fn['name']}**: "
                     f"requires [{'; '.join(fn.get('requires', [])) or '—'}], "
                     f"ensures [{'; '.join(fn.get('ensures', [])) or '—'}]")
    lines += ["", "## Properties", ""]
    for p in spec.get("properties", []):
        acc = (" — accepted without evidence: " + p["accept_note"]
               if p["evidence"] == "none" and p.get("accepted") else "")
        lines.append(f"- **{p['id']}**: {p['text']} "
                     f"(evidence: {p['evidence']}){acc}")
    with open(P["spec_md"], "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    return unanswered


def cmd_build(intent_path):
    spec, d, P = paths_for(intent_path)
    module = spec["module"]

    # THE FORCING: unevidenced property without a signed
    # acceptance stops the build before anything is generated.
    unsigned = [p for p in spec.get("properties", [])
                if p["evidence"] == "none" and not p.get("accepted")]
    if unsigned:
        for p in unsigned:
            print(f"REFUSED: property '{p['id']}' has no evidence and no "
                  "signed acceptance. Declare evidence or set "
                  "\"accepted\": true with an accept_note.")
        return 1

    rs_text = gen_module(spec)
    with open(P["rs"], "w", encoding="utf-8") as f:
        f.write(rs_text)
    module_file = os.path.basename(P["rs"])

    results = {}  # property id -> (tier, result, note)
    ledger = {"module": module, "contracts": [], "functions": []}
    for s in spec.get("structs", []):
        if s.get("invariant"):
            ledger["contracts"].append(
                {"kind": "invariant", "owner": s["name"],
                 "text": s["invariant"], "tier": "runtime-checked"})
    for fn in spec.get("functions", []):
        entry = {"name": fn["name"], "requires": len(fn.get("requires", [])),
                 "ensures": len(fn.get("ensures", []))}
        ledger["functions"].append(entry)
        for r in fn.get("requires", []):
            ledger["contracts"].append(
                {"kind": "requires", "owner": fn["name"], "text": r,
                 "tier": "runtime-checked"})
        for e in fn.get("ensures", []):
            ledger["contracts"].append(
                {"kind": "ensures", "owner": fn["name"], "text": e,
                 "tier": "runtime-checked"})

    with tempfile.TemporaryDirectory() as td:
        scen_rs = os.path.join(d, f"axiomi_tmp_{module}_scen.rs")
        ver_rs = os.path.join(d, f"axiomi_tmp_{module}_ver.rs")
        try:
            with open(scen_rs, "w", encoding="utf-8") as f:
                f.write(gen_scenario_main(spec, module_file))
            rc, err = rustc_build(scen_rs, os.path.join(td, "scen"))
            if rc != 0:
                print(f"axiomi: scenario build failed:\n{err}",
                      file=sys.stderr)
                return 1
            p = subprocess.run([os.path.join(td, "scen")],
                               capture_output=True, text=True)
            for prop in spec.get("properties", []):
                if prop["evidence"] == "scenario":
                    ok = f"PROP {prop['id']} OK" in p.stdout
                    results[prop["id"]] = (
                        "runtime-checked", "PASS" if ok else "FAIL",
                        "scenario snippet against generated Rust")
            with open(ver_rs, "w", encoding="utf-8") as f:
                f.write(gen_verify_main(spec, module_file))
            rc, err = rustc_build(ver_rs, os.path.join(td, "ver"))
            if rc != 0:
                print(f"axiomi: verify build failed:\n{err}",
                      file=sys.stderr)
                return 1
            p = subprocess.run([os.path.join(td, "ver")],
                               capture_output=True, text=True)
            for prop in spec.get("properties", []):
                if prop["evidence"] == "verify":
                    m = re.search(
                        rf"VERIFY {prop['fn']} cases=(\d+) excluded=(\d+) "
                        rf"failed=(\d+)", p.stdout)
                    if m and int(m.group(3)) == 0:
                        results[prop["id"]] = (
                            "bounded", "PASS",
                            f"exhausted: {m.group(1)} cases, "
                            f"{m.group(2)} excluded by requires")
                    else:
                        note = ("domain too large" if "DOMAIN_TOO_LARGE"
                                in p.stdout else "counterexample found")
                        results[prop["id"]] = ("bounded", "FAIL", note)
        finally:
            for tmp in (scen_rs, ver_rs):
                if os.path.exists(tmp):
                    os.unlink(tmp)

    for prop in spec.get("properties", []):
        if prop["evidence"] == "none":
            results[prop["id"]] = (
                "none", "UNCHECKED (accepted)",
                prop.get("accept_note", ""))

    unanswered = write_spec_md(spec, P)
    with open(intent_path, encoding="utf-8") as f:
        intent_hash = sha(f.read())
    lock = {"intent_sha256": intent_hash, "artifact_sha256": sha(rs_text)}
    with open(P["lock"], "w", encoding="utf-8") as f:
        json.dump(lock, f, indent=1)
    ledger["integrity"] = "IN-LOOP"
    ledger["results"] = {k: {"tier": v[0], "result": v[1], "note": v[2]}
                         for k, v in results.items()}
    with open(P["ledger"], "w", encoding="utf-8") as f:
        json.dump(ledger, f, indent=1, ensure_ascii=False)

    ev = [f"# Evidence: {module}", "",
          f"Target: generated Rust (`{module}.rs`, artifact, do not edit). "
          f"Contracts in ledger: {len(ledger['contracts'])}. "
          f"Decisions: {len(spec.get('decisions', [])) - len(unanswered)} "
          f"answered, {len(unanswered)} on default. "
          "Integrity: IN-LOOP.",
          "", "| property | tier | result | note |", "|---|---|---|---|"]
    failed = 0
    for prop in spec.get("properties", []):
        tier, result, note = results[prop["id"]]
        if result == "FAIL":
            failed += 1
        ev.append(f"| {prop['id']} | {tier} | {result} | {note} |")
    ev += ["", "## Unchecked / accepted risks", ""]
    risks = [pid for pid, v in results.items() if v[1].startswith("UNCHECKED")]
    for pid in risks:
        ev.append(f"- property `{pid}` accepted without evidence")
    for d in unanswered:
        ev.append(f"- decision `{d['id']}` still on default `{d['default']}`")
    uncovered = [f["name"] for f in ledger["functions"]
                 if f["requires"] == 0 and f["ensures"] == 0]
    for name in uncovered:
        ev.append(f"- function `{name}` declares no contracts")
    if not risks and not unanswered and not uncovered:
        ev.append("- none")
    with open(P["evidence_md"], "w", encoding="utf-8") as f:
        f.write("\n".join(ev) + "\n")

    passed = sum(1 for v in results.values() if v[1] == "PASS")
    print(f"axiomi: {module}: {passed} passed, {failed} failed, "
          f"{len(risks)} unchecked-accepted, {len(unanswered)} decisions "
          "on default; artifact IN-LOOP")
    return 1 if failed else 0


def main():
    if len(sys.argv) != 3 or sys.argv[1] not in ("build", "check"):
        print("usage: axiomi.py build|check <name>.intent.json",
              file=sys.stderr)
        return 2
    if sys.argv[1] == "build":
        return cmd_build(sys.argv[2])
    return cmd_check(sys.argv[2])


if __name__ == "__main__":
    sys.exit(main())
